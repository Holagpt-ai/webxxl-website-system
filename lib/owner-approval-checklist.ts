export function getOwnerReviewCatalog(projectId: string): OwnerReviewCatalogItem[] | null {
  if (projectId !== ABMED_CLINICAL_RESEARCH_REVIEW_PROJECT_ID) return null
  return abmedOwnerReviewCatalog
}

export function hasOwnerReviewPackage(projectId: string | null | undefined): boolean {
  return Boolean(projectId && getOwnerReviewCatalog(projectId))
}

